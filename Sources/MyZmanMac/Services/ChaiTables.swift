    /// The site's city for a location, if there is an obvious one.
    static func city(for location: Location) -> String? {
        guard location.region == .israel else { return nil }
        if let a = aliases[location.nameHe] { return a }
        let name = location.nameHe.replacingOccurrences(of: " ", with: "_")
        return cities.contains(name) ? name : nil
    }

    static func displayName(_ city: String) -> String { city.replacingOccurrences(of: "_", with: " ") }

    /// The table of visible sunrise and sunset for a city and Hebrew year, as the site shows it.
    static func tableURL(city: String, hebrewYear: Int, sefard: Bool) -> URL {
        let items: [(String, String)] = [
            ("cgi_TableType", "BY"), ("cgi_country", "Eretz Yisroel"), ("cgi_USAcities1", "1"), ("cgi_USAcities2", "0"),
            ("cgi_searchradius", ""), ("cgi_Placename", "?"), ("cgi_eroslatitude", "0.0"), ("cgi_eroslongitude", "0.0"),
            ("cgi_eroshgt", "0.0"), ("cgi_geotz", "2"), ("cgi_exactcoord", "OFF"), ("cgi_MetroArea", city),
            ("cgi_types", "6"),   // visible sunrise and sunset
            ("cgi_RoundSecond", "-1"), ("cgi_AddCushion", "0"), ("cgi_24hr", "ON"), ("cgi_DST", "ON"),
            ("cgi_typezman", "-1"), ("cgi_yrheb", String(hebrewYear)), ("cgi_optionheb", "0"), ("cgi_UserNumber", "413"),
            ("cgi_Language", "Hebrew"), ("cgi_sefira", "OFF"), ("cgi_nusach", sefard ? "ON" : "OFF"),
            ("cgi_Moladim", "OFF"), ("cgi_AllowShaving", "OFF"),
        ]
        var c = URLComponents(string: "http://www.chaitables.com/cgi-bin/ChaiTables.cgi/")!
        c.queryItems = items.map { URLQueryItem(name: $0.0, value: $0.1) }
        return c.url!
    }

    static func currentHebrewYear(in tz: TimeZone) -> Int {
        var hebrew = Calendar(identifier: .hebrew)
        hebrew.timeZone = tz
        return hebrew.component(.year, from: Date())
    }
